-- 1. Create the moments table
create table if not exists public.moments (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    user_id uuid default auth.uid() references auth.users(id) on delete set null,
    user_email text,
    user_name text,
    user_avatar text,
    image_url text not null,
    file_path text,
    title text
);

-- 2. Enable Row Level Security (RLS)
alter table public.moments enable row level security;

-- Drop existing policies if re-running script
drop policy if exists "Public can read moments" on public.moments;
drop policy if exists "Authenticated users can insert moments" on public.moments;
drop policy if exists "Users can update own moments" on public.moments;
drop policy if exists "Users can delete own moments" on public.moments;

-- Policy 1: Anyone (including visitors) can view moments
create policy "Public can read moments"
    on public.moments
    for select
    using (true);

-- Policy 2: Only logged-in students can upload moments
create policy "Authenticated users can insert moments"
    on public.moments
    for insert
    with check (auth.role() = 'authenticated');

-- Policy 3: Students can update their own moments
create policy "Users can update own moments"
    on public.moments
    for update
    using (auth.uid() = user_id);

-- Policy 4: Students can delete their own moments
create policy "Users can delete own moments"
    on public.moments
    for delete
    using (auth.uid() = user_id);

-- 3. Create Storage bucket for class photos (if not exists)
insert into storage.buckets (id, name, public)
values ('class-moments', 'class-moments', true)
on conflict (id) do update set public = true;

-- Drop existing storage policies if re-running
drop policy if exists "Public access to class photos" on storage.objects;
drop policy if exists "Authenticated students can upload photos" on storage.objects;
drop policy if exists "Students can delete own photos" on storage.objects;

-- Policy 1: Anyone can view photos
create policy "Public access to class photos"
    on storage.objects
    for select
    using (bucket_id = 'class-moments');

-- Policy 2: Authenticated students can upload photos
create policy "Authenticated students can upload photos"
    on storage.objects
    for insert
    with check (
        bucket_id = 'class-moments'
        and auth.role() = 'authenticated'
    );

-- Policy 3: Students can delete their own photos
create policy "Students can delete own photos"
    on storage.objects
    for delete
    using (
        bucket_id = 'class-moments'
        and (auth.uid()::text = (storage.foldername(name))[1])
    );

-- 4. Enable Realtime on the moments table so new uploads appear live
-- (Idempotent: safely checks if already added so it never throws an error on re-run)
do $$
begin
    if not exists (
        select 1 from pg_publication_tables 
        where pubname = 'supabase_realtime' 
        and schemaname = 'public' 
        and tablename = 'moments'
    ) then
        alter publication supabase_realtime add table public.moments;
    end if;
end $$;

